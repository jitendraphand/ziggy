"""Recursive QA/QC loop: regenerate -> test -> (on failure) clean-regenerate -> retest, bounded.

Exit 0 only if all tests and release gates pass within MAX_ROUNDS. Writes a versioned
validation report to docs/validation/. Fixes requiring engineering judgement are NOT
automated: the loop stops, reports, and blocks release.
"""
import datetime, json, platform, shutil, subprocess, sys
from pathlib import Path

MAX_ROUNDS = 3
ROOT = Path(__file__).resolve().parents[1]

def run(cmd):
    print("+", " ".join(cmd), flush=True)
    return subprocess.run(cmd, cwd=ROOT).returncode

def regenerate(clean=False):
    if clean:
        for d in ("hardware/step", "hardware/stl"):
            shutil.rmtree(ROOT/d, ignore_errors=True)
    return run([sys.executable, "-m", "cad.build"]) or run([sys.executable, "-m", "ziggy.mjcf"])

def metrics():
    sys.path.insert(0, str(ROOT))
    import os; os.chdir(ROOT)
    import mujoco, cadquery
    from ziggy import __version__
    from ziggy.analysis import ik_benchmark, household_reach, stance_sim, static_torque_cases
    st = stance_sim(5.0); st.pop("steady_torques_nm")
    push = stance_sim(5.0, push_n=40.0); push.pop("steady_torques_nm")
    tq = static_torque_cases()
    over = {c: {n: r for n, r in rows.items() if r["ratio_rated"] >= 0.8} for c, rows in tq.items()}
    return {"version": __version__, "date": datetime.date.today().isoformat(),
            "env": {"python": platform.python_version(), "mujoco": mujoco.__version__, "cadquery": cadquery.__version__},
            "ik_left": ik_benchmark(200, 0, "l"), "ik_right": ik_benchmark(200, 0, "r"),
            "household_reach_residual_mm": household_reach("l"),
            "pd_stance_5s": st, "pd_stance_40N_0.1s_push": push,
            "torque_ratio_ge_0.8_of_rated": over}

def report(rounds, ok, m):
    v = m["version"]; out = ROOT/"docs"/"validation"
    out.mkdir(parents=True, exist_ok=True)
    (out/f"v{v}.json").write_text(json.dumps({"rounds": rounds, "passed": ok, **m}, indent=2) + "\n")
    lines = [f"# Validation report v{v} (simulation & design checks only)", "",
             f"Generated by `tools/qa.py` on {m['date']}. Rounds used: {rounds}/{MAX_ROUNDS}. Gate: **{'PASS' if ok else 'FAIL'}**.",
             "", "**No physical hardware has been built or tested.** Every result below is simulated or geometric.", "",
             "```json", json.dumps({k: m[k] for k in m if k not in ("version", "date")}, indent=2), "```", ""]
    (out/f"v{v}.md").write_text("\n".join(lines))

def main():
    ok = False
    for rnd in range(1, MAX_ROUNDS + 1):
        print(f"=== QA round {rnd} ===")
        if regenerate(clean=rnd > 1) != 0:
            continue
        if run([sys.executable, "-m", "pytest", "-q", "tests"]) == 0:
            ok = True; break
    report(rnd, ok, metrics())
    print("QA", "PASS" if ok else "FAIL (release blocked)")
    sys.exit(0 if ok else 1)

if __name__ == "__main__":
    main()
